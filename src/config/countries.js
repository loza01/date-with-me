export const nationalityLabel = (country, detail) => {
  const label = NATIONALITY_BY_COUNTRY[country] ?? country
  return country === AFRICAN && detail ? `${label} (${detail})` : label
}

export const residenceLabel = (country, detail) => {
  const label = country === 'United States' ? 'United States of America' : country === AFRICAN ? 'Africa' : country
  return country === AFRICAN && detail ? `${label} (${detail})` : label
}

